# ---------------------------------------------------------------------------
# Ratio / derived detection (non-additive, AD-4) and physical data_type.
# ---------------------------------------------------------------------------

_RATIO_PREFIXES = ("CPC_", "CPM_", "CPV_", "CPCV_", "ECP", "ECTR", "CTR",
                   "OUTBOUND_CTR", "COST_PER_")
_RATIO_MARKERS = ("_RATE", "ROAS", "_CTR", "FREQUENCY", "AVERAGE", "_AVG_",
                  "COST_PER_ACTION")


def _is_ratio_or_derived(name: str) -> bool:
    """True for provider-computed ratio/derived metrics (never SUM -- AD-4)."""
    if name.startswith(_RATIO_PREFIXES):
        return True
    if name in ("CTR", "CTR_2", "ECTR", "EENGAGEMENT_RATE", "ENGAGEMENT_RATE",
                "REPIN_RATE", "TOTAL_REPIN_RATE", "TOTAL_IMPRESSION_FREQUENCY"):
        return True
    return any(marker in name for marker in _RATIO_MARKERS)


# ---------------------------------------------------------------------------
# Section assignment (ordered, first match wins) -- transposed from the
# research draft _section_note name families.
# ---------------------------------------------------------------------------


def _dimension_section(name: str) -> str:
    if name in PRODUCT_ITEM_DIMS:
        return S_PRODUCT_ITEM
    if name == "VIDEO_LENGTH":
        return S_VIDEO
    return S_ENTITY


def _metric_section(name: str) -> str:
    if "_ACTION_TO_" in name and name.endswith("_CONVERSION"):
        return S_DEVICE_PATH
    if "WEB_SESSION" in name:
        return S_WEB_SESSIONS
    if "COLLECTION_PIN_ITEM" in name:
        return S_COLLECTION
    if name.startswith(("TOTAL_VIDEO_", "VIDEO_")) or name in (
        "ECPV_IN_DOLLAR", "ECPCV_IN_DOLLAR", "ECPCV_P95_IN_DOLLAR",
    ):
        return S_VIDEO
    if _is_ratio_or_derived(name):
        return S_PERFORMANCE
    if name.endswith("_VALUE_IN_MICRO_DOLLAR"):
        return S_CONVERSION_VALUE
    if name.startswith(("SPEND_", "ADS_CREDIT_")):
        return S_SPEND
    if name in ("PAID_IMPRESSION", "TOTAL_IMPRESSION", "TOTAL_IMPRESSION_USER") or (
        name.startswith("IMPRESSION_")
    ):
        return S_IMPRESSION
    if name == "TOTAL_CLICKTHROUGH" or name.startswith(
        ("CLICKTHROUGH_", "OUTBOUND_CLICK_")
    ):
        return S_CLICKTHROUGH
    if name.startswith(("SHOWCASE_", "QUIZ_")) or name in (
        "TOTAL_ENGAGEMENT", "ENGAGEMENT_1", "ENGAGEMENT_2", "REPIN_1", "REPIN_2",
    ):
        return S_ENGAGEMENT
    # Everything left is a conversion-event family count/quantity
    # (TOTAL_<EVENT>*, ONSITE_*, INAPP_*, IDEA_PIN_*, LEADS, ...).
    return S_CONVERSION


_DECIMAL_METRICS = frozenset((
    "TOTAL_VIDEO_AVG_WATCHTIME_IN_SECOND",
))


def _metric_data_type(name: str) -> str:
    if name.endswith("_IN_MICRO_DOLLAR") or "_IN_MICRO_DOLLAR_" in name:
        return "int"  # int64 micro-currency on the wire; landed as value/1e6
    if "_IN_DOLLAR" in name:
        return "currency"
    if _is_ratio_or_derived(name) or name in _DECIMAL_METRICS:
        return "decimal"
    return "int"  # count metrics


_DIM_TYPE_OVERRIDES: dict[str, str] = {
    "CAMPAIGN_DAILY_SPEND_CAP": "int",     # micro-currency cap (int64)
    "CAMPAIGN_LIFETIME_SPEND_CAP": "int",  # micro-currency cap (int64)
    "AD_GROUP_BUDGET_IN_LOCAL_CURRENCY": "currency",
    "AD_GROUP_BID_MULTIPLIER": "decimal",
    "VIDEO_LENGTH": "decimal",
    "IS_CATALOG_CREATIVE_CAMPAIGN": "boolean",
    "IS_PREMIERE_CAMPAIGN": "boolean",
}


def _dimension_data_type(name: str) -> str:
    return _DIM_TYPE_OVERRIDES.get(name, "string")


_MICROS_NOTE = (
    " int64 micro-currency amount on the wire (1e-6 of the ad account"
    " currency); landed as value/1e6 (platform micros rule, story 26.3 --"
    " the connector derives its conversion set from THIS catalog marker,"
    " never from an id-suffix heuristic)."
)
_RATIO_NOTE = (
    " Provider-computed ratio/derived metric: NON-ADDITIVE (AD-4) -- never"
    " SUM across rows; recompute at the semantic layer from stored"
    " numerators and denominators."
)
_MUTABLE_NOTE = (
    " DESCRIPTIVE MUTABLE (story 26.6 Part A): an entity STATE/TYPE attribute"
    " that changes over time for a fixed grain -- landed in attributes_json"
    " (latest-wins), NEVER in the segments_json supersede grain key, so a"
    " refetch that re-reads a window with a changed status does not double the"
    " metrics of that window."
)


def build() -> list[dict]:
    """Return the official snapshot entries (deterministic, sorted)."""
    if len(ASYNC_COLUMNS) != EXPECTED_ASYNC_COUNT:
        raise ValueError(
            f"async enum count drifted: {len(ASYNC_COLUMNS)} != {EXPECTED_ASYNC_COUNT}"
        )
    if len(set(ASYNC_COLUMNS)) != EXPECTED_ASYNC_COUNT:
        raise ValueError("duplicate column in ASYNC_COLUMNS")
    if len(SYNC_ALSO) != EXPECTED_SYNC_ALSO_COUNT:
        raise ValueError(
            f"sync-also count drifted: {len(SYNC_ALSO)} != {EXPECTED_SYNC_ALSO_COUNT}"
        )
    if len(DIMENSIONS) != EXPECTED_DIMENSION_COUNT:
        raise ValueError(
            f"dimension count drifted: {len(DIMENSIONS)} != {EXPECTED_DIMENSION_COUNT}"
        )
    if not SYNC_ALSO <= set(ASYNC_COLUMNS):
        raise ValueError("SYNC_ALSO must be a subset of ASYNC_COLUMNS")
    if not DIMENSIONS <= set(ASYNC_COLUMNS):
        raise ValueError("DIMENSIONS must be a subset of ASYNC_COLUMNS")
    if len(DESCRIPTIVE_MUTABLE) != EXPECTED_DESCRIPTIVE_MUTABLE_COUNT:
        raise ValueError(
            f"descriptive_mutable count drifted: {len(DESCRIPTIVE_MUTABLE)} != "
            f"{EXPECTED_DESCRIPTIVE_MUTABLE_COUNT}"
        )
    # Every descriptive_mutable field MUST be a declared dimension (a metric can
    # never be an entity attribute) and MUST NOT be a grain-bearing id.
    if not DESCRIPTIVE_MUTABLE <= DIMENSIONS:
        raise ValueError(
            "DESCRIPTIVE_MUTABLE must be a subset of DIMENSIONS: "
            f"{sorted(DESCRIPTIVE_MUTABLE - DIMENSIONS)}"
        )
    if any(name.endswith("_ID") for name in DESCRIPTIVE_MUTABLE):
        raise ValueError(
            "a grain-bearing *_ID must never be descriptive_mutable: "
            f"{sorted(n for n in DESCRIPTIVE_MUTABLE if n.endswith('_ID'))}"
        )

    out: list[dict] = []

    def add(field_id, kind, data_type, section, description, source_field,
            descriptive_mutable=False):
        entry = {
            "field_id": field_id,
            "kind": kind,
            "data_type": data_type,
            "description": description,
            "section": section,
            "source_field": source_field,
        }
        if descriptive_mutable:
            # Story 26.6 Part A: landed in attributes_json (latest-wins), NEVER
            # in the segments_json supersede grain key.
            entry["descriptive_mutable"] = True
        out.append(entry)

    for name in ASYNC_COLUMNS:
        is_dim = name in DIMENSIONS
        kind = "dimension" if is_dim else "metric"
        reach = (
            "Requestable via the async report path AND the sync analytics"
            " endpoints (ReportingColumnSync member)."
            if name in SYNC_ALSO
            else "Requestable via the async report path only"
            " (POST /ad_accounts/{id}/reports; not in ReportingColumnSync)."
        )
        desc = (
            f"Pinterest Ads reporting column '{name}'"
            " (ReportingColumnAsync, OpenAPI 5.28.0). " + reach
        )
        is_mutable = name in DESCRIPTIVE_MUTABLE
        if is_dim:
            desc += " Entity attribute (dimension) of the report row."
            data_type = _dimension_data_type(name)
            section = _dimension_section(name)
            if is_mutable:
                desc += _MUTABLE_NOTE
        else:
            data_type = _metric_data_type(name)
            section = _metric_section(name)
            if data_type == "int" and (
                name.endswith("_IN_MICRO_DOLLAR") or "_IN_MICRO_DOLLAR_" in name
            ):
                desc += _MICROS_NOTE
            if _is_ratio_or_derived(name):
                desc += _RATIO_NOTE
        add(name, kind, data_type, section, desc, name,
            descriptive_mutable=is_mutable)

    # The single sync-only column (union member #627).
    add(
        "QUIZ_PIN_RESULT_OPEN",
        "metric",
        "int",
        S_ENGAGEMENT,
        "Pinterest Ads reporting column 'QUIZ_PIN_RESULT_OPEN'"
        " (ReportingColumnSync, OpenAPI 5.28.0). SYNC-ONLY: the one column of"
        " the sync enum ABSENT from ReportingColumnAsync -- NOT requestable"
        " through the async report path that catalog_daily uses (excluded"
        " with reason in the generated catalog; reachable when a sync-columns"
        " profile lands).",
        "QUIZ_PIN_RESULT_OPEN",
    )

    # The structural grain dimension of the report response (NOT an enum
    # value, never sent in `columns`): granularity DAY stamps a DATE key on
    # every row.
    add(
        "date",
        "dimension",
        "date",
        S_TIME,
        "Reporting day (UTC date, 'DATE' key of the report response row at"
        " granularity DAY). Structural grain dimension -- not a"
        " ReportingColumn enum value; it is never sent in the request's"
        " 'columns' array.",
        "DATE",
    )

    out.sort(key=lambda e: e["field_id"])
    return out


# ---------------------------------------------------------------------------
# field_compatibility (core schema "1") -- one selectable_set rule per
# whitelisted catalog_daily level, regenerated in catalog_sources.json.
# ---------------------------------------------------------------------------


def build_field_compatibility() -> dict:
    metrics = sorted(
        name for name in ASYNC_COLUMNS if name not in DIMENSIONS
    )
    rules = []
    for level in sorted(LEVEL_DIMS):
        allowed = sorted(set(metrics) | LEVEL_DIMS[level] | {"date"})
        rules.append({
            "id": f"level_selectable_{level.lower()}",
            "kind": "selectable_set",
            "scope": {"level": level},
            "allowed_fields": allowed,
            "_note": (
                f"Columns selectable in an async report at level={level}:"
                " every async metric + the entity-attribute dimensions of"
                f" the {level} lineage + the date grain."
                " QUIZ_PIN_RESULT_OPEN (sync-only) and PRODUCT_ITEM_*"
                " attributes are reachable at NO whitelisted level (typed"
                " pre-call refusal)."
            ),
        })
    return {
        "schema_version": "1",
        "_note": (
            "Story 26.3 -- GENERATED by build_official_fields.py (do not edit"
            " by hand; regen keeps the rules in lockstep with the enum)."
            " Core contract (field-compatibility.schema.json, 26.1):"
            " selectable_set rules scoped {'level': <LEVEL>} consumed by"
            " core.field_compat.enforce_selection with"
            " context={'level': ...} BEFORE any API call. Date-window /"
            " granularity limits are request-parameter validation (not field"
            " rules): see _request_limits."
        ),
        "_source": (
            "POST /ad_accounts/{ad_account_id}/reports endpoint description +"
            " per-level response attributes, OpenAPI 5.28.0"
        ),
        "rules": rules,
    }


def build_descriptive_mutable() -> dict:
    """Story 26.6 Part A: the DERIVED descriptive_mutable block for
    catalog_sources.json.

    The connector reads THIS block (not api_catalog.json -- whose core schema
    forbids extra field keys, and which is out-of-scope to change) to decide
    which landed columns leave segments_json for attributes_json. The list is
    the OFFICIAL enum ids; the connector maps them to their canonical landed
    names through the same manifest rename map transform() uses, so a mutable
    attribute is recognised whether it lands under its enum id or its canonical
    name (e.g. CAMPAIGN_ENTITY_STATUS -> campaign_status).
    """
    return {
        "schema_version": "1",
        "_note": (
            "Story 26.6 Part A -- GENERATED by build_official_fields.py (do not"
            " edit by hand). Entity STATE/TYPE dimensions that mutate over time"
            " for a fixed grain: the connector lands them in attributes_json"
            " (latest-wins, HORS partition) instead of segments_json (the"
            " QUALIFY supersede grain key), so a refetch re-reading a window"
            " with a changed status does not double the window's metrics."
            " Grain-bearing ids and conversion/device-path metrics are NEVER"
            " listed here."
        ),
        "field_ids": sorted(DESCRIPTIVE_MUTABLE),
    }


def main() -> None:
    fields = build()
    metrics = sum(1 for f in fields if f["kind"] == "metric")
    dims = sum(1 for f in fields if f["kind"] == "dimension")
    here = Path(__file__).parent

    out_path = here / "official_fields.json"
    out_path.write_text(
        json.dumps(fields, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    # Regenerate the field_compatibility + descriptive_mutable blocks in
    # catalog_sources.json (both kept in lockstep with the enum).
    sources_path = here / "catalog_sources.json"
    sources = json.loads(sources_path.read_text(encoding="utf-8"))
    sources["field_compatibility"] = build_field_compatibility()
    sources["descriptive_mutable"] = build_descriptive_mutable()
    sources_path.write_text(
        json.dumps(sources, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    print(
        f"Wrote {len(fields)} fields ({metrics} metrics / {dims} dimensions;"
        f" union of the official enums = {EXPECTED_UNION_COUNT} + 1 date grain;"
        f" {len(DESCRIPTIVE_MUTABLE)} descriptive_mutable) to {out_path};"
        f" field_compatibility + descriptive_mutable regenerated in {sources_path}"
    )


if __name__ == "__main__":
    main()
