# ---------------------------------------------------------------------------
# DESCRIPTIVE_MUTABLE (Story 26.6 Part A) -- entity STATE/TYPE dimensions whose
# value MUTATES over time for a fixed grain key (a campaign paused, an ad group
# objective retargeted). They are attributes of the entity, NOT row-bearing
# breakdowns: two different values for the SAME (date, entity) are the SAME
# fact restated, latest-wins -- never two rows to keep.
#
# The refetch ladder (26.1) re-pulls historical windows nightly; without this
# marking a status flip between two pulls would produce a NEW segments_json and
# the stale row would survive the QUALIFY supersede, DOUBLING every metric of
# the re-pulled window. So the CONNECTOR lands these OUT of segments_json (the
# grain key) into a SEPARATE attributes_json column (hors partition, latest-
# wins), exactly as campaign_name already behaves.
#
# Prudent default (story contract): a dimension carrying an entity STATUS /
# ENTITY_STATUS / MANAGED_STATUS, or an OBJECTIVE_TYPE / BUDGET_TYPE, is
# descriptive_mutable. What is DELIBERATELY EXCLUDED and stays in the grain:
#   - grain-bearing ids (CAMPAIGN_ID, AD_GROUP_ID, AD_ID, PIN_ID,
#     PRODUCT_GROUP_ID, ORDER_LINE_ID...) -- they DEFINE the row;
#   - the 99 CONVERSION DEVICE PATH metrics and every conversion-family metric
#     -- they are VALUES, not entity attributes (never here);
#   - names (CAMPAIGN_NAME...) already land latest-wins outside segments_json
#     via the structural columns, so they are not re-listed here.
# A dimension NOT in this set keeps the conservative catalog behaviour (grain).
