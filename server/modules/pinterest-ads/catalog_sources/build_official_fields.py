"""Deterministic builder for pinterest-ads official_fields.json (Story 26.3).

This script is the AUDITABLE SOURCE for the committed official snapshot. It is
committed alongside its outputs (official_fields.json + the regenerated
``field_compatibility`` rules inside catalog_sources.json) so a reviewer can
see exactly how the curated column space was derived from the official
Pinterest REST API v5 OpenAPI spec (pinterest/api-description, pinned 5.28.0)
recorded in catalog_sources.json.

It is pure-Python, deterministic (no network, no clock), and byte-stable:
running it again reproduces both outputs exactly.

Derivation summary (see catalog_sources.json "_derivation"):
  - ASYNC_COLUMNS = the INTEGRAL ``ReportingColumnAsync`` enum (626 values, in
    spec order -- research dossier Annex A, fetched 2026-07-21). ZERO
    truncation (story 26.3 hard rule: 627 columns, zero planned).
  - SYNC_ALSO   = the 184 columns also present in ``ReportingColumnSync``
    (Annex A ``[S]`` markers). ReportingColumnSync totals 185 values: these
    184 + the single sync-only column below.
  - SYNC_ONLY   = ``QUIZ_PIN_RESULT_OPEN`` -- the ONE column of the sync enum
    absent from the async enum. Union async+sync = 627 official columns.
  - DIMENSIONS  = the 53 entity-attribute columns (Annex A ``[dim]`` markers,
    curated: ids/names/statuses/labels/caps/product-item attributes). They are
    declared kind=dimension; every other enum value is a metric.
  - ``date``    = the ONE structural grain dimension of the report response
    (``DATE`` key, granularity DAY). It is NOT an enum value -- it is never
    sent in ``columns`` -- so the catalog totals 628 entries = 627 official
    columns + this grain dimension.
  - NO EXPANSION RULE: unlike Meta action-families, Pinterest pre-flattens
    every conversion family x attribution split x unit variant and the
    99-column device-path family directly into the enum. The enum IS the flat
    catalog.
  - Sections are assigned from the ordered name-family rules below (the
    OpenAPI spec carries no sections); micro-currency columns
    (*_IN_MICRO_DOLLAR) carry the ``value/1e6`` landing marker in their
    description -- the CONNECTOR derives its unit-conversion set from that
    catalog marker, never from an id-suffix heuristic (google-ads review
    lesson, 26.2).
  - This script ALSO regenerates catalog_sources.json's ``field_compatibility``
    rules (core schema "1", one selectable_set rule per whitelisted report
    level) so the pre-call refusal contract can never drift from the column
    space.

Run (orchestrator, local only -- outputs are committed):
    uv run python server/modules/pinterest-ads/catalog_sources/build_official_fields.py
"""

