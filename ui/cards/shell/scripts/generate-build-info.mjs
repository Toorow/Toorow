/**
 * Story 50.5 AC14 -- write the runtime's build identity into a module the bundle
 * can import.
 *
 * The identity itself is defined by `runtime-identity.mjs`; read its docstring
 * for why it is a content hash of `src/viz/**` and not a git SHA.
 *
 * IT IS COMMITTED, AND IT IS NOT REWRITTEN BY A TEST RUN. Those two facts are the
 * same fact: a content hash only moves when the runtime moves, so the generated
 * file is stable under every other session's commits, and `tsc --noEmit` works on
 * a fresh checkout with no git and no build step -- which is why it stays tracked
 * rather than gitignored. What used to justify gitignoring it was the git SHA
 * changing on every commit anywhere in the repository; that cause is gone.
 *
 * A STALE FILE IS A RED TEST, NOT A SILENT LIE. `__tests__/buildInfo.test.ts`
 * recomputes the identity from disk and refuses a mismatch, so editing the
 * runtime and forgetting to regenerate fails loudly. That guard is what the
 * `pretest` hook used to pretend to be while actually just overwriting the file
 * -- and overwriting it is why nothing could ever notice it was wrong.
 *
 * IT IS HALF OF ONE GESTURE, NEVER RUN ALONE. The identity is carried by TWO
 * generated files -- this one and `src/viz/rendererBuilds.generated.json` -- and
 * a repository that can regenerate one without the other grows exactly the drift
 * measured on 2026-08-24, three identities two generations apart. The single
 * gesture is `pnpm --filter @toorow/card-shell generate:build-identity`, which
 * runs this script and then `emit-renderer-builds.mjs`, in that order because the
 * manifest stamps the identity this script writes.
 *
 * Run: pnpm --filter @toorow/card-shell generate:build-identity  (also
 * `prebuild`).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { PACKAGE_ROOT, runtimeIdentity } from "./runtime-identity.mjs";

const { semver, contentHash } = runtimeIdentity();

const contents = `/* GENERATED by scripts/generate-build-info.mjs -- do not edit.
 * Regenerate with \`pnpm --filter @toorow/card-shell generate:build-identity\`,
 * which also re-emits src/viz/rendererBuilds.generated.json: the two carry ONE
 * identity and are never regenerated apart.
 * The hash covers src/viz/** (see scripts/runtime-identity.mjs), so it moves
 * only when the runtime moves. */
export const RUNTIME_SEMVER = ${JSON.stringify(semver)};
export const RUNTIME_CONTENT_HASH = ${JSON.stringify(contentHash)};
`;

const target = join(PACKAGE_ROOT, "src", "viz", "buildInfo.generated.ts");
writeFileSync(target, contents, "utf8");
process.stdout.write(`buildInfo.generated.ts <- ${semver}+${contentHash}\n`);
